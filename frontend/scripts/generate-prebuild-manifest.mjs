import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const ENV_PATH = path.join(ROOT, ".env.local");
const OUT_DIR = path.join(ROOT, "src", "generated");
const OUT_FILE = path.join(OUT_DIR, "prebuild-manifest.ts");

const PRODUCTION_API_FALLBACK = "https://streamflix-04zq.onrender.com/api";
const LOCAL_API_FALLBACK = "http://localhost:5000/api";

async function loadEnvLocal() {
  let text;
  try {
    text = await readFile(ENV_PATH, "utf8");
  } catch {
    return;
  }

  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    const separator = trimmed.indexOf("=");
    if (separator === -1) continue;

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (!key || process.env[key] !== undefined) continue;

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    process.env[key] = value;
  }
}

function getApiBaseUrl() {
  const isProduction =
    process.env.NODE_ENV === "production" || process.env.NETLIFY === "true";
  const fallback = isProduction ? PRODUCTION_API_FALLBACK : LOCAL_API_FALLBACK;
  let url = (process.env.NEXT_PUBLIC_API_URL || fallback).trim();
  url = url.replace(/\/+$/, "");
  if (!url.endsWith("/api")) {
    url = `${url}/api`;
  }
  return url;
}

async function fetchJson(endpoint) {
  const url = `${getApiBaseUrl()}${endpoint}`;
  const headers = { Accept: "application/json" };
  if (process.env.API_SECRET) {
    headers["X-API-Key"] = process.env.API_SECRET;
  }

  const response = await fetch(url, {
    headers,
    // No timeout: Render can cold-start for longer than a runtime request.
    // The old build path deliberately waited instead of failing the build.
  });

  if (!response.ok) {
    throw new Error(
      `[prebuild] ${endpoint} failed: ${response.status} ${response.statusText}. ` +
        `Check NEXT_PUBLIC_API_URL and API_SECRET.`
    );
  }

  return response.json();
}

function inferType(item, forcedType) {
  if (forcedType) return forcedType;
  if (item.media_type === "movie" || item.media_type === "tv") {
    return item.media_type;
  }
  if (item.media_type === "person") {
    return null;
  }
  return item.name && !item.title ? "tv" : "movie";
}

function addItem(byKey, item, forcedType) {
  const mediaType = inferType(item, forcedType);
  if (!mediaType) return;

  const title = item.title || item.name;
  if (!title) return;

  byKey.set(`${mediaType}:${item.id}`, {
    id: item.id,
    media_type: mediaType,
    title,
  });
}

async function main() {
  await loadEnvLocal();

  const buckets = [
    { endpoint: "/media/trending" },
    { endpoint: "/media/top-picks", type: "tv" },
    { endpoint: "/media/fan-favorites" },
    { endpoint: "/media/genre/movie/28", type: "movie" },
    { endpoint: "/media/genre/tv/18", type: "tv" },
    { endpoint: "/media/genre/movie/35", type: "movie" },
    { endpoint: "/media/genre/movie/53", type: "movie" },
    { endpoint: "/media/genre/tv/10765", type: "tv" },
    { endpoint: "/media/genre/tv/80", type: "tv" },
    { endpoint: "/media/genre/tv/9648", type: "tv" },
  ];

  const [results, catalog] = await Promise.all([
    Promise.all(buckets.map((bucket) => fetchJson(bucket.endpoint))),
    fetchJson("/curated/catalog"),
  ]);

  const byKey = new Map();

  results.forEach((result, index) => {
    const items = result.results || [];
    for (const item of items) {
      addItem(byKey, item, buckets[index].type);
    }
  });

  for (const item of catalog) {
    if (
      !item?.id ||
      (item.media_type !== "movie" && item.media_type !== "tv")
    ) {
      continue;
    }
    byKey.set(`${item.media_type}:${item.id}`, {
      id: item.id,
      media_type: item.media_type,
      title: item.title || "details",
    });
  }

  const items = Array.from(byKey.values()).sort((a, b) => {
    if (a.media_type !== b.media_type) {
      return a.media_type.localeCompare(b.media_type);
    }
    return a.title.localeCompare(b.title);
  });

  if (items.length === 0) {
    throw new Error(
      "[prebuild] The pre-render catalog is empty. Refusing to build without static detail pages."
    );
  }

  await mkdir(OUT_DIR, { recursive: true });

  const generated = `// AUTO-GENERATED by scripts/generate-prebuild-manifest.mjs.
// Do not edit by hand. Run \`npm run prebuild\` to regenerate.
export interface PrebuildManifestItem {
  id: number;
  media_type: "movie" | "tv";
  title: string;
}

export const PREBUILD_ITEMS: PrebuildManifestItem[] = ${JSON.stringify(items, null, 2)};
`;

  await writeFile(OUT_FILE, generated, "utf8");
  console.log(
    `[prebuild] Wrote ${items.length} static detail pages to ${path.relative(ROOT, OUT_FILE)}`
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
